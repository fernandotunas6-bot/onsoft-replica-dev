/**
 * SIGA Global Subjects Registry — disciplinas e unidades curriculares de
 * referência.
 *
 * Uma entrada aqui é a disciplina «em abstracto»: nome canónico, sinónimos,
 * área ISCED-F e os níveis ISCED em que costuma existir. Não diz que um país
 * a tem num ano concreto, nem a carga horária ou a avaliação — isso é do
 * plano curricular (stages.ts), que muda por país, curso, classe e versão.
 *
 * `levels` é o contexto de nível: uma pesquisa feita para o Ensino Primário
 * não sugere «Termodinâmica», e uma feita para o Superior não sugere
 * «Estudo do Meio».
 *
 * Os códigos das disciplinas do ensino geral angolano são os mesmos dos
 * modelos de estrutura (curriculum-templates.ts), para as escolas que já
 * os usam continuarem a bater certo.
 */
