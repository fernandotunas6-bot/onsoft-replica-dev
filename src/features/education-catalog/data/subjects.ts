export const GLOBAL_SUBJECTS: readonly GlobalSubject[] = ROWS.map(
  ([code, name, short, aliases, field, levels, tracks, extra]) => ({
    code,
    name,
    short,
    aliases,
    field,
    levels,
    tracks,
    ...extra,
  }),
);

const BY_CODE = new Map(GLOBAL_SUBJECTS.map((s) => [s.code, s]));

export function globalSubject(code: string) {
  return BY_CODE.get(code);
}

/** Nome a mostrar num país (ex.: «Português» em Portugal, «Língua Portuguesa» em Angola). */
export function subjectDisplayName(subject: GlobalSubject, countryCode?: string | null) {
  return (countryCode && subject.localNames?.[countryCode.toUpperCase()]) || subject.name;
}
